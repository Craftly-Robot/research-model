"""Agentic tool-calling and multi-step defensive verification protocol.

Defines schemas, parsers, and dataset structures for Craftly's agentic workflows.
The model reasons with thoughts, invokes allowlisted tools (<|tool_call|>),
observes results (<|tool_result|>), and synthesizes safe unified diff patches
(<|patch_start|> ... <|patch_end|>).
"""

from __future__ import annotations

import json
import re
from typing import Any

from pydantic import Field

from src.craftly.shared.schemas import StrictModel

TOOL_CALL_START = "<|tool_call|>"
TOOL_CALL_END = "<|tool_end|>"
TOOL_RESULT_START = "<|tool_result|>"
TOOL_RESULT_END = "<|tool_result_end|>"
THOUGHT_START = "<|thought_start|>"
THOUGHT_END = "<|thought_end|>"
PATCH_START = "<|patch_start|>"
PATCH_END = "<|patch_end|>"


class ToolDefinition(StrictModel):
    """Specification of an allowlisted defensive tool."""

    name: str = Field(pattern=r"^(test|git_diff|shell)$")
    description: str = Field(min_length=1)
    parameters_schema: dict[str, Any] = Field(default_factory=dict)


class ToolCall(StrictModel):
    """A concrete tool call generated by the model."""

    tool: str = Field(pattern=r"^(test|git_diff|shell)$")
    command: list[str] = Field(min_length=1)
    timeout_ms: int = Field(default=30_000, ge=1_000, le=120_000)


class ToolResult(StrictModel):
    """Structured execution output returned to the model."""

    tool: str
    status: str = Field(pattern=r"^(ok|failed|timeout|error)$")
    exit_code: int | None = None
    stdout: str = ""
    stderr: str = ""
    duration_ms: float = 0.0


class ParsedAgentStep(StrictModel):
    """Deconstructed model response step."""

    thought: str | None = None
    tool_call: ToolCall | None = None
    patch: str | None = None
    explanation: str | None = None
    is_terminal: bool = False


def format_tool_call(call: ToolCall) -> str:
    """Format a ToolCall into delimited syntax."""
    payload = {"tool": call.tool, "command": call.command, "timeout_ms": call.timeout_ms}
    return f"{TOOL_CALL_START}{json.dumps(payload)}{TOOL_CALL_END}"


def format_tool_result(result: ToolResult) -> str:
    """Format a ToolResult into delimited observation syntax."""
    payload = {
        "tool": result.tool,
        "status": result.status,
        "exit_code": result.exit_code,
        "stdout": result.stdout.strip()[:10_000],
        "stderr": result.stderr.strip()[:10_000],
    }
    return f"{TOOL_RESULT_START}{json.dumps(payload)}{TOOL_RESULT_END}"


def parse_agentic_output(text: str) -> ParsedAgentStep:
    """Parse thoughts, tool calls, and patches from model generation."""
    thought = None
    tool_call = None
    patch = None

    # 1. Parse Thought
    thought_match = re.search(r"<\|thought_start\|>(.*?)<\|thought_end\|>", text, re.DOTALL)
    if thought_match:
        thought = thought_match.group(1).strip()

    # 2. Parse Tool Call
    call_match = re.search(r"<\|tool_call\|>(.*?)<\|tool_end\|>", text, re.DOTALL)
    if call_match:
        raw_json = call_match.group(1).strip()
        try:
            data = json.loads(raw_json)
            tool_call = ToolCall(**data)
        except Exception:
            pass

    # 3. Parse Patch
    patch_match = re.search(r"<\|patch_start\|>(.*?)<\|patch_end\|>", text, re.DOTALL)
    if patch_match:
        patch = patch_match.group(1).strip()

    # Clean explanation text
    cleaned = text
    if thought_match:
        cleaned = cleaned.replace(thought_match.group(0), "")
    if call_match:
        cleaned = cleaned.replace(call_match.group(0), "")
    if patch_match:
        cleaned = cleaned.replace(patch_match.group(0), "")

    is_terminal = patch is not None or (tool_call is None and len(cleaned.strip()) > 0)
    return ParsedAgentStep(
        thought=thought,
        tool_call=tool_call,
        patch=patch,
        explanation=cleaned.strip() or None,
        is_terminal=is_terminal,
    )


